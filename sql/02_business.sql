-- NearSlot 业务表（v1）幂等脚本
USE nearslot;

-- 用户
CREATE TABLE IF NOT EXISTS user (
  id BIGINT PRIMARY KEY COMMENT '雪花ID',
  nickname VARCHAR(64) NOT NULL DEFAULT '',
  password VARCHAR(128) NOT NULL DEFAULT '' COMMENT 'BCrypt',
  level TINYINT NOT NULL DEFAULT 1 COMMENT '会员等级 1-10',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  deleted TINYINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户';

CREATE TABLE IF NOT EXISTS user_info (
  user_id BIGINT PRIMARY KEY,
  avatar VARCHAR(255) NOT NULL DEFAULT '',
  city VARCHAR(64) NOT NULL DEFAULT '',
  level TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户档案';

CREATE TABLE IF NOT EXISTS user_phone (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NOT NULL,
  phone VARCHAR(20) NOT NULL,
  UNIQUE KEY uk_user_phone (phone),
  KEY idx_user_phone_uid (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='手机号（HASH_MOD）';

-- 服务商
CREATE TABLE IF NOT EXISTS shop (
  id BIGINT PRIMARY KEY,
  name VARCHAR(128) NOT NULL,
  type_id BIGINT NOT NULL DEFAULT 0,
  x DOUBLE NOT NULL DEFAULT 0 COMMENT '经度',
  y DOUBLE NOT NULL DEFAULT 0 COMMENT '纬度',
  address VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  KEY idx_shop_type (type_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='服务商';

CREATE TABLE IF NOT EXISTS technician (
  id BIGINT PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  name VARCHAR(64) NOT NULL,
  level TINYINT NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_tech_shop (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='技师';

CREATE TABLE IF NOT EXISTS service_item (
  id BIGINT PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  name VARCHAR(128) NOT NULL,
  duration_min INT NOT NULL DEFAULT 60,
  price_cent INT NOT NULL DEFAULT 0 COMMENT '分',
  KEY idx_item_shop (shop_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='服务项';

-- 时段：唯一约束是防重复预约最后防线（research/08 §2）
CREATE TABLE IF NOT EXISTS time_slot (
  id BIGINT PRIMARY KEY,
  shop_id BIGINT NOT NULL,
  technician_id BIGINT NOT NULL,
  service_item_id BIGINT NOT NULL DEFAULT 0,
  starts_at DATETIME NOT NULL COMMENT 'UTC 时刻',
  ends_at DATETIME NOT NULL,
  tz_id VARCHAR(64) NOT NULL DEFAULT 'Asia/Shanghai',
  capacity INT NOT NULL DEFAULT 1,
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1可约 2关闭',
  version INT NOT NULL DEFAULT 0 COMMENT '乐观锁',
  min_level INT NOT NULL DEFAULT 0 COMMENT '预约所需最低会员等级，0=无门槛',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT uq_slot_occupy UNIQUE (technician_id, starts_at),
  KEY idx_slot_shop_time (shop_id, starts_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='时段定义';

CREATE TABLE IF NOT EXISTS time_slot_stock (
  slot_id BIGINT PRIMARY KEY,
  capacity INT NOT NULL DEFAULT 1,
  sold INT NOT NULL DEFAULT 0,
  version INT NOT NULL DEFAULT 0,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='时段余量（DB 兜底）';

-- 预约单（分片，按 user_id）
CREATE TABLE IF NOT EXISTS appointment_order (
  id BIGINT PRIMARY KEY COMMENT '预约单号（雪花）',
  user_id BIGINT NOT NULL,
  slot_id BIGINT NOT NULL,
  shop_id BIGINT NOT NULL,
  technician_id BIGINT NOT NULL,
  status TINYINT NOT NULL DEFAULT 1 COMMENT '1待支付 2已确认 3已取消 4已完成 5已退款',
  amount_cent INT NOT NULL DEFAULT 0,
  hold_expires_at DATETIME NULL COMMENT 'Hold 过期时刻',
  reconcile_status TINYINT NULL COMMENT '对账状态 1待对账 2不一致 4已一致',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT uq_user_slot UNIQUE (user_id, slot_id),
  KEY idx_order_user (user_id),
  KEY idx_order_slot (slot_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='预约单';

CREATE TABLE IF NOT EXISTS appointment_order_router (
  order_id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  slot_id BIGINT NOT NULL,
  ds_name VARCHAR(16) NOT NULL,
  tbl_suffix VARCHAR(8) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='订单路由表';

CREATE TABLE IF NOT EXISTS appointment_reconcile_log (
  id BIGINT PRIMARY KEY,
  order_id BIGINT NOT NULL,
  log_type TINYINT NOT NULL COMMENT '1BOOK 2RESTORE',
  result TINYINT NOT NULL COMMENT '1SUCCESS 2FAIL',
  before_qty INT NOT NULL DEFAULT 0,
  change_qty INT NOT NULL DEFAULT 0,
  after_qty INT NOT NULL DEFAULT 0,
  trace_id BIGINT NULL,
  remark VARCHAR(255) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_rec_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='对账日志';

CREATE TABLE IF NOT EXISTS rollback_failure_log (
  id BIGINT PRIMARY KEY,
  order_id BIGINT NOT NULL,
  reason VARCHAR(255) NOT NULL DEFAULT '',
  payload TEXT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_rf_order (order_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='回滚失败兜底（全局广播表）';

CREATE TABLE IF NOT EXISTS reminder_queue_log (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  slot_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  sent_at DATETIME NULL,
  dedup_key VARCHAR(128) NOT NULL,
  UNIQUE KEY uk_reminder_dedup (dedup_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='延迟提醒去重';

-- AI
CREATE TABLE IF NOT EXISTS agent_conversation (
  id BIGINT PRIMARY KEY,
  user_id BIGINT NOT NULL,
  title VARCHAR(128) NOT NULL DEFAULT '',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_conv_user (user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 会话';

CREATE TABLE IF NOT EXISTS agent_message (
  id BIGINT PRIMARY KEY,
  conversation_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  role VARCHAR(16) NOT NULL,
  content TEXT NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_msg_conv (conversation_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='AI 回合';
